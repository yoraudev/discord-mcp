import { execFileSync, spawn } from 'node:child_process';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const npm = process.env.npm_execpath;
if (!npm) throw new Error('Run this check with npm run package:check.');
const installEnvironment = Object.fromEntries(Object.entries(process.env).filter(([key]) => !/^npm_config_allow[_-]?scripts/i.test(key)));
installEnvironment.npm_config_ignore_scripts = 'true';
const directory = resolve('.cache', `package-check-${crypto.randomUUID()}`);
await mkdir(directory, { recursive: true });
const packed = JSON.parse(execFileSync(process.execPath, [npm, 'pack', '--json', '--ignore-scripts'], { encoding: 'utf8' }));
const tarball = resolve(packed[0].filename);
await writeFile(resolve(directory, 'package.json'), JSON.stringify({ name: 'discord-mcp-install-check', version: '1.0.0', private: true }));
execFileSync(process.execPath, [npm, 'install', '--offline', '--ignore-scripts', '--no-audit', '--no-fund', tarball], { cwd: directory, stdio: 'inherit', env: installEnvironment });
const installed = resolve(directory, 'node_modules/@yoraudev/discord-mcp');
const entry = resolve(installed, 'dist/index.js');
await readFile(entry);
await readFile(resolve(installed, 'dist/reference/discord.json'));
await readFile(resolve(installed, 'LICENSE'));
const child = spawn(process.execPath, [entry], { cwd: directory, env: { ...process.env, DISCORD_MCP_OFFLINE: '1' }, stdio: ['pipe', 'pipe', 'pipe'] });
let output = '';
let errors = '';
child.stdout.on('data', data => { output += data; if (output.includes('"id":1')) child.stdin.end(); });
child.stderr.on('data', data => { errors += data; });
const timeout = setTimeout(() => { child.kill(); }, 15000);
child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'installed-package-check', version: '1.0.0' } } }) + '\n');
await new Promise((resolve, reject) => { child.once('error', reject); child.once('exit', code => code === 0 ? resolve() : reject(new Error(`Installed server exited ${code}: ${errors}`))); });
clearTimeout(timeout);
if (errors || !output.includes('discord-mcp')) throw new Error(`Installed server failed handshake: ${errors} ${output}`);
console.log(`Verified installed package: ${tarball}`);
